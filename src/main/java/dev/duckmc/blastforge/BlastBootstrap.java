package dev.duckmc.blastforge;

import io.papermc.paper.plugin.bootstrap.BootstrapContext;
import io.papermc.paper.plugin.bootstrap.PluginBootstrap;
import io.papermc.paper.plugin.lifecycle.event.types.LifecycleEvents;
import io.papermc.paper.registry.RegistryKey;
import io.papermc.paper.registry.TypedKey;
import io.papermc.paper.registry.data.EnchantmentRegistryEntry;
import io.papermc.paper.registry.event.RegistryEvents;
import io.papermc.paper.registry.keys.EnchantmentKeys;
import io.papermc.paper.registry.keys.tags.ItemTypeTagKeys;
import io.papermc.paper.registry.keys.tags.EnchantmentTagKeys;
import net.kyori.adventure.key.Key;
import net.kyori.adventure.text.Component;
import org.bukkit.enchantments.Enchantment;
import org.bukkit.inventory.EquipmentSlotGroup;
import java.util.Set;
import java.util.HashSet;
import io.papermc.paper.registry.tag.TagKey;
import org.bukkit.inventory.ItemType;

public final class BlastBootstrap implements PluginBootstrap {
    public static final TypedKey<Enchantment> BLAST = EnchantmentKeys.create(Key.key("blastforge:blast"));
    private static final TagKey<ItemType> BLAST_TOOLS=TagKey.create(RegistryKey.ITEM,Key.key("blastforge:blast_tools"));
    @Override public void bootstrap(BootstrapContext context) {
        context.getLifecycleManager().registerEventHandler(LifecycleEvents.TAGS.postFlatten(RegistryKey.ITEM),event -> {
            var tools=new HashSet<>(event.registrar().getTag(ItemTypeTagKeys.PICKAXES));
            tools.addAll(event.registrar().getTag(ItemTypeTagKeys.SHOVELS));
            event.registrar().setTag(BLAST_TOOLS,tools);
        });
        context.getLifecycleManager().registerEventHandler(RegistryEvents.ENCHANTMENT.compose(), event ->
            event.registry().register(BLAST, b -> b.description(Component.text("Blast"))
                .supportedItems(event.getOrCreateTag(BLAST_TOOLS))
                .primaryItems(event.getOrCreateTag(BLAST_TOOLS))
                .anvilCost(4).maxLevel(3).weight(1)
                .minimumCost(EnchantmentRegistryEntry.EnchantmentCost.of(10,12))
                .maximumCost(EnchantmentRegistryEntry.EnchantmentCost.of(60,10))
                .activeSlots(EquipmentSlotGroup.MAINHAND)));
        context.getLifecycleManager().registerEventHandler(LifecycleEvents.TAGS.postFlatten(RegistryKey.ENCHANTMENT), event -> {
            event.registrar().addToTag(EnchantmentTagKeys.IN_ENCHANTING_TABLE, Set.of(BLAST));
            // Librarian Blast offers are generated by ForgeItems with weighted
            // levels. Vanilla's uniform level selection must not bypass them.
            event.registrar().addToTag(EnchantmentTagKeys.NON_TREASURE, Set.of(BLAST));
        });
    }
}
