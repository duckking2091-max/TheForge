    boolean perk(Player player,String needed) {
        boolean full=cfg().getString("armor-perks.activation","any-piece").equalsIgnoreCase("full-set");
        boolean inherit=cfg().getBoolean("armor-perks.inherit",true);int count=0;
        for(ItemStack armor:player.getInventory().getArmorContents()) {
            String id=items.id(armor);String tier=ExpansionItems.tier(id);
            if(ExpansionItems.isArmor(ExpansionItems.piece(id)) && (tier.equals(needed) || inherit && ExpansionItems.TIERS.indexOf(tier)>ExpansionItems.TIERS.indexOf(needed)))count++;
        }
        return full?count==4:count>0;
    }
    /** An ore buried in rock gets no overlay: entities draw through terrain the client has culled, which would act like X-ray. */
    private static boolean exposed(Block block){
        for(var face:List.of(org.bukkit.block.BlockFace.UP,org.bukkit.block.BlockFace.DOWN,org.bukkit.block.BlockFace.NORTH,org.bukkit.block.BlockFace.SOUTH,org.bukkit.block.BlockFace.EAST,org.bukkit.block.BlockFace.WEST)){
            int y=block.getY()+face.getModY();if(y<block.getWorld().getMinHeight()||y>=block.getWorld().getMaxHeight())continue;
            try{Block n=block.getRelative(face);if(!n.getWorld().isChunkLoaded(n.getX()>>4,n.getZ()>>4))continue;if(!n.getType().isOccluding())return true;}catch(RuntimeException outsideStoredHeight){continue;}
        }
        return false;
    }
