    private void rebuild(Chunk chunk) {
        // Reconstructed entities are not authoritative and never saved; remove stale duplicates.
        for(Entity entity:chunk.getEntities())if(entity.getPersistentDataContainer().has(OVERLAY))entity.remove();
        String prefix=chunk.getWorld().getUID()+":";
        displays.entrySet().removeIf(entry->{ItemDisplay d=entry.getValue();return !d.isValid() || d.getWorld().equals(chunk.getWorld()) && d.getLocation().getBlockX()>>4==chunk.getX() && d.getLocation().getBlockZ()>>4==chunk.getZ();});
        if(!cfg().getBoolean("ore-visuals.enabled",true))return;
        int total=Math.clamp(cfg().getInt("ore-visuals.max-displays",2048),0,4096),perChunk=Math.clamp(cfg().getInt("ore-visuals.max-per-chunk",64),0,256),count=0;
        String chunkId=chunkKey(chunk.getWorld().getUID(),chunk.getX(),chunk.getZ());
        // Snapshot a bounded slice: even a heavily player-filled chunk cannot create an unbounded render pass.
        for(var entry:owned(chunkId).entrySet().stream().limit(256).map(e->Map.entry(e.getKey(),e.getValue())).toList()) {
            if(count>=perChunk || displays.size()>=total)break;
            String[] xyz=entry.getKey().split(":");if(xyz.length!=3)continue;
            Block block=chunk.getWorld().getBlockAt(Integer.parseInt(xyz[0]),Integer.parseInt(xyz[1]),Integer.parseInt(xyz[2]));
            if(!isOre(block) || !exposed(block))continue;
            ItemDisplay display=chunk.getWorld().spawn(block.getLocation().add(.5,.5,.5),ItemDisplay.class,d->{
                d.setPersistent(false);d.setInvulnerable(true);d.setGravity(false);d.setViewRange(4);d.setDisplayWidth(1);d.setDisplayHeight(1);
                d.setTransformation(new org.bukkit.util.Transformation(new org.joml.Vector3f(),new org.joml.Quaternionf(),new org.joml.Vector3f(1.002f),new org.joml.Quaternionf()));
                d.setItemStack(items.create(entry.getValue()+"_ore"));d.setItemDisplayTransform(ItemDisplay.ItemDisplayTransform.NONE);
                d.getPersistentDataContainer().set(OVERLAY,PersistentDataType.BYTE,(byte)1);d.setVisibleByDefault(false);
            });
            for(Player viewer:chunk.getWorld().getPlayers())visibility(viewer,display);
            displays.put(prefix+entry.getKey(),display);count++;
        }
    }
    @EventHandler public void unloaded(ChunkUnloadEvent event) {
        Chunk chunk=event.getChunk();String key=chunkKey(chunk.getWorld().getUID(),chunk.getX(),chunk.getZ());synchronized(pending){pending.remove(key);}cache.remove(key);
        var iterator=displays.values().iterator();while(iterator.hasNext()) {ItemDisplay display=iterator.next();if(display.getWorld().equals(chunk.getWorld()) && (display.getLocation().getBlockX()>>4)==chunk.getX() && (display.getLocation().getBlockZ()>>4)==chunk.getZ()){display.remove();iterator.remove();}}
    }
