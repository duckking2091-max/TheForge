    // ---- Slow mining -------------------------------------------------------------------------------
    // While a player digs an ore, a temporary BLOCK_BREAK_SPEED multiplier makes it take the configured time.
    // Vanilla: damage per tick = tool speed / hardness / 30. Netherite + Efficiency V has speed 9 + 26 = 35.
    // Siftie (deepslate-diamond-ore carrier, hardness 4.5): 10 s with netherite Eff V.
    // Enderite (ancient-debris carrier, hardness 30): 20 s with netherite Eff V, 15 s with a Siftie (or better) pickaxe Eff V.
    private static final NamespacedKey SLOW=ExpansionItems.key("ore_mining_time");
    private final Set<UUID> slowed=java.util.concurrent.ConcurrentHashMap.newKeySet();
    double multiplier(String tier,Player player,ItemStack tool){return multiplier(tier,player,tool,tier.equals("siftie")?4.5:30);}
    double multiplier(String tier,Player player,ItemStack tool,double hardness){
        if(tier.equals("siftie"))return hardness*30/(20.0*cfg().getDouble("mining-seconds.siftie",10)*35);
        String toolTier=items.equipmentTier(tool);boolean custom=List.of("siftie","enderite","wardenite").contains(toolTier)&&items.equipmentPiece(tool).equals("pickaxe");
        double seconds=custom?cfg().getDouble("mining-seconds.enderite-with-siftie",15):cfg().getDouble("mining-seconds.enderite",20);
        double m=hardness*30/(20.0*seconds*35);
        if(custom){var attribute=attr(player);double current=attribute==null?1:attribute.getValue();m/=Math.max(.01,current);} // cancel the tool's own speed bonus so every custom pickaxe takes the same time
        return m;
    }
    private void slow(Player player,double multiplier){
        var attribute=attr(player);if(attribute==null)return;
        clearSlow(player);attribute.addTransientModifier(new org.bukkit.attribute.AttributeModifier(SLOW,multiplier-1,org.bukkit.attribute.AttributeModifier.Operation.MULTIPLY_SCALAR_1));slowed.add(player.getUniqueId());
    }
    private void clearSlow(Player player){
        if(!slowed.remove(player.getUniqueId()))return;var attribute=attr(player);if(attribute!=null)attribute.removeModifier(SLOW);
    }
    @EventHandler(priority=EventPriority.HIGH,ignoreCancelled=true) public void digStart(BlockDamageEvent e){
        String tier=tier(e.getBlock());if(tier.isEmpty()||e.getPlayer().getGameMode()==GameMode.CREATIVE){clearSlow(e.getPlayer());return;}
        /* The slow-down only applies after the first hit, so a fast enough pickaxe (Wardenite + Efficiency V) would break Enderite on that hit. */
        if(tier.equals("enderite")&&items.equipmentTier(e.getItemInHand()).equals("wardenite"))e.setInstaBreak(false);
        clearSlow(e.getPlayer());slow(e.getPlayer(),multiplier(tier,e.getPlayer(),e.getItemInHand(),e.getBlock().getType().getHardness()));
    }
