    private void own(Block block,String tier) {
        String chunk=chunkKey(block),key=local(block);
        store.put("material_ore:"+chunk,key,tier);owned(chunk).put(key,tier);
    }
    private void forget(Block block) {
        String chunk=chunkKey(block),key=local(block);
        store.remove("material_ore:"+chunk,key);owned(chunk).remove(key);
        ItemDisplay display=displays.remove(position(block));if(display!=null)display.remove();
    }
    @EventHandler public void chunkLoaded(ChunkLoadEvent event){
        enqueue(event.getChunk(),event.isNewChunk());
        // Ores on the edge of an already-loaded neighbour may only now count as exposed; redo their overlays.
        Chunk c=event.getChunk();for(int[] d:new int[][]{{1,0},{-1,0},{0,1},{0,-1}})if(c.getWorld().isChunkLoaded(c.getX()+d[0],c.getZ()+d[1]))enqueue(c.getWorld().getChunkAt(c.getX()+d[0],c.getZ()+d[1]),false);
    }
    private void enqueue(Chunk chunk,boolean generate) {
        String key=chunkKey(chunk.getWorld().getUID(),chunk.getX(),chunk.getZ());
        synchronized(pending){   // filled from every region's chunk-load events
            if(pending.size()>=QUEUE_LIMIT && !pending.containsKey(key))return;
            PendingChunk before=pending.get(key);
            pending.put(key,new PendingChunk(chunk.getWorld().getUID(),chunk.getX(),chunk.getZ(),generate || before!=null && before.generate()));
        }
    }
    private void tick() {
        int max=Math.clamp(cfg().getInt("generation.max-chunks-per-tick",2),1,8);
        var batch=new ArrayList<PendingChunk>();
        synchronized(pending){for(int i=0;i<max && !pending.isEmpty();i++){var iterator=pending.entrySet().iterator();batch.add(iterator.next().getValue());iterator.remove();}}
        for(PendingChunk entry:batch){
            World world=plugin.getServer().getWorld(entry.world());if(world==null)continue;
            // each chunk's ores are placed and drawn on the thread that owns that chunk
            dev.duckmc.blastforge.Tasks.nowAt(plugin,new Location(world,entry.x()*16+8,64,entry.z()*16+8),()->{
                if(!running || !world.isChunkLoaded(entry.x(),entry.z()))return;
                Chunk chunk=world.getChunkAt(entry.x(),entry.z());
                if(entry.generate())generate(chunk);
                rebuild(chunk);
            });
        }
    }
    private void generate(Chunk chunk) {
        World world=chunk.getWorld();String tier=world.getEnvironment()==World.Environment.NORMAL?"siftie":world.getEnvironment()==World.Environment.THE_END?"enderite":"";
        if(tier.isEmpty())return;
        String key=chunkKey(world.getUID(),chunk.getX(),chunk.getZ());
        if(store.get("material_chunks",key)!=null)return;
        // Record first so neither repeated ChunkLoadEvents nor a crash can repeat rewards in this chunk.
        store.put("material_chunks",key,"1");
        String path="generation."+tier+".";if(!cfg().getBoolean(path+"enabled",true)||!items.tierEnabled(tier))return;
        double distance=Math.max(0,cfg().getDouble("generation.enderite.minimum-distance",1024));
        if(tier.equals("enderite") && Math.hypot(chunk.getX()*16.0+8,chunk.getZ()*16.0+8)<distance)return;
        int min=Math.max(world.getMinHeight(),cfg().getInt(path+"min-y",tier.equals("siftie")?-60:20));
        int max=Math.min(world.getMaxHeight()-1,cfg().getInt(path+"max-y",tier.equals("siftie")?-30:70));
        if(max<min)return;
        int attempts=Math.clamp(cfg().getInt(path+"attempts",1),0,16);
        int maxVein=Math.clamp(cfg().getInt(path+"vein-size",tier.equals("siftie")?3:5),1,16);
        Random random=new Random(world.getSeed()^((long)chunk.getX()*341873128712L)^((long)chunk.getZ()*132897987541L));
        /* Like ancient debris, underground Enderite only replaces end stone that is fully buried (hide-from-air). */
        boolean hidden=tier.equals("enderite")&&cfg().getBoolean(path+"hide-from-air",true);
        java.util.function.Predicate<Block> host=b->tier.equals("siftie")?Set.of(Material.STONE,Material.DEEPSLATE,Material.TUFF).contains(b.getType()):b.getType()==Material.END_STONE&&!(hidden&&exposed(b));
        // chance: how often each attempt really makes a vein (Siftie is rarer than diamonds: by default 1 vein in ~4 chunks)
        double chance=Math.clamp(cfg().getDouble(path+"chance",tier.equals("siftie")?.25:1),0,1);
        // exposed-chance: how often a vein is placed on a cave wall (visible) instead of buried in stone
        double exposedChance=Math.clamp(cfg().getDouble(path+"exposed-chance",tier.equals("siftie")?.3:1),0,1);
        for(int n=0;n<attempts;n++) {
            int x=random.nextInt(16),z=random.nextInt(16),y=min+random.nextInt(max-min+1);
            boolean make=random.nextDouble()<chance,visible=random.nextDouble()<exposedChance;
            if(!make)continue;
            // Some veins start on a cave wall or open surface so players can spot them; the rest stay buried.
            int tries=visible?Math.clamp(cfg().getInt(path+"visible-search",tier.equals("siftie")?48:0),0,256):0;
            for(int t=0;t<tries;t++){int tx=random.nextInt(16),tz=random.nextInt(16),ty=min+random.nextInt(max-min+1);Block c=chunk.getBlock(tx,ty,tz);if(host.test(c)&&exposed(c)){x=tx;y=ty;z=tz;break;}}
            vein(chunk,key,tier,host,random,x,y,z,min,max,1+random.nextInt(maxVein));
        }
        if(tier.equals("enderite")){
            // Extra veins lying on top of the outer islands, not only inside them.
            // Very rare, like exposed ancient debris: by default about 1 chunk in 100, and only 1-2 blocks.
            int surface=random.nextDouble()<Math.clamp(cfg().getDouble(path+"surface-chance",.01),0,1)?1:0;
            int surfaceSize=Math.clamp(cfg().getInt(path+"surface-vein-size",2),1,16);
            for(int n=0;n<surface;n++){int x=random.nextInt(16),z=random.nextInt(16);
                for(int y=Math.min(max,world.getMaxHeight()-2);y>=min;y--){Block c=chunk.getBlock(x,y,z);if(c.getType()==Material.END_STONE&&c.getRelative(0,1,0).getType().isAir()){surfaceVein(chunk,key,tier,random,x,y,z,1+random.nextInt(surfaceSize));break;}}
            }
        }
    }
    private void vein(Chunk chunk,String key,String tier,java.util.function.Predicate<Block> host,Random random,int x,int y,int z,int min,int max,int size){
        for(int v=0;v<size;v++) {
            Block block=chunk.getBlock(x,y,z);
            // Each accepted block is durably owned before changing the world.
            if(host.test(block) && !owned(key).containsKey(local(block))) {own(block,tier);block.setType(carrier(tier),false);}
            switch(random.nextInt(6)) {case 0->x=Math.min(15,x+1);case 1->x=Math.max(0,x-1);case 2->z=Math.min(15,z+1);case 3->z=Math.max(0,z-1);case 4->y=Math.min(max,y+1);default->y=Math.max(min,y-1);}
        }
    }
    /** Spreads along the top layer of an island: each block must be end stone with open air above it. */
    private void surfaceVein(Chunk chunk,String key,String tier,Random random,int x,int y,int z,int size){
        for(int v=0;v<size*3&&size>0;v++){
            Block block=chunk.getBlock(x,y,z);
            if(block.getType()==Material.END_STONE&&block.getRelative(0,1,0).getType().isAir()&&!owned(key).containsKey(local(block))){own(block,tier);block.setType(carrier(tier),false);size--;}
            int nx=Math.clamp(x+random.nextInt(3)-1,0,15),nz=Math.clamp(z+random.nextInt(3)-1,0,15);
            for(int dy=1;dy>=-1;dy--){Block c=chunk.getBlock(nx,Math.clamp(y+dy,chunk.getWorld().getMinHeight(),chunk.getWorld().getMaxHeight()-2),nz);if(c.getType()==Material.END_STONE&&c.getRelative(0,1,0).getType().isAir()){x=nx;z=nz;y=c.getY();break;}}
        }
    }
