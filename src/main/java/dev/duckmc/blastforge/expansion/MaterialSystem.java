    @EventHandler(priority=EventPriority.MONITOR,ignoreCancelled=true)
    public void breakOre(BlockBreakEvent event) {
        Block block=event.getBlock();String tier=tier(block);if(tier.isEmpty())return;
        String position=position(block);if(!breaking.add(position))return;
        ItemStack tool=event.getPlayer().getInventory().getItemInMainHand().clone();
        boolean rewards=event.getPlayer().getGameMode()!=GameMode.CREATIVE && canMine(block,tool) && items.tierEnabled(tier);   // a turned-off tier's leftover ore gives nothing
        event.setDropItems(false);event.setExpToDrop(0);
        dev.duckmc.blastforge.Tasks.at(plugin,block,()->{
            breaking.remove(position);
            if(event.isCancelled() || isCarrier(tier,block.getType()))return;
            // Remove persistent reward ownership before issuing the single custom drop.
            forget(block);
            if(!rewards)return;
            ItemStack drop=items.create(tool.getEnchantmentLevel(Enchantment.SILK_TOUCH)>0?tier+"_ore":tier.equals("siftie")?"raw_siftie":"enderite_scrap");
            if(tool.getEnchantmentLevel(Enchantment.SILK_TOUCH)==0) {
                int fortune=Math.clamp(tool.getEnchantmentLevel(Enchantment.FORTUNE),0,10);
                drop.setAmount(Math.max(1,ThreadLocalRandom.current().nextInt(fortune+2)));
            }
            block.getWorld().dropItemNaturally(block.getLocation().add(.5,.5,.5),drop);
        });
    }
