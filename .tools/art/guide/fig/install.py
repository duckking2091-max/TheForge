import json,os,shutil
PROJ='/tmp/claude-0/build/proj';OUT='/tmp/claude-0/art/figs/out'
FIG=json.load(open(OUT+'/figures.json'));LINES,FIRST,LH,BASE=11,6,9,0xE400
tex=PROJ+'/resource-pack/assets/blastforge/textures/font/guide/fig';os.makedirs(tex,exist_ok=True)
art=PROJ+'/.tools/art/guide/fig';os.makedirs(art,exist_ok=True)
fp=PROJ+'/resource-pack/assets/blastforge/font/guide.json';font=json.load(open(fp))
font['providers']=[p for p in font['providers'] if not p.get('file','').startswith('blastforge:font/guide/fig/')]
props=['# generated by .tools/art/guide/fig: name = index, width, height (pixels)']
for i,(name,(w,h)) in enumerate(sorted(FIG.items())):
    shutil.copy(f'{OUT}/{name}.png',f'{tex}/{name}.png');shutil.copy(f'{OUT}/{name}.png',f'{art}/{name}.png')
    for row in range(LINES):
        top=FIRST+LH*row
        if top+h>FIRST+LINES*LH:break
        font['providers'].append({'type':'bitmap','file':f'blastforge:font/guide/fig/{name}.png','ascent':13-top,'height':h,'chars':[chr(BASE+i*LINES+row)]})
    props.append(f'{name}={i},{w},{h}')
json.dump(font,open(fp,'w'),indent=1)
open(PROJ+'/src/main/resources/guide_figures.properties','w').write('\n'.join(props)+'\n')
print(len(FIG),'figures,',len(font['providers']),'providers')
